create table if not exists public.workers (
  id bigint generated by default as identity primary key,
  nama text not null,
  kategori text not null,
  kecamatan text not null,
  tarif_harian integer not null,
  no_wa text not null,
  is_verified boolean not null default false,
  is_available boolean not null default true,
  rating numeric(2, 1) not null default 0,
  total_job integer not null default 0,
  deskripsi text,
  pengalaman text,
  keahlian text[] not null default '{}',
  portofolio text,
  reviews jsonb not null default '[]'::jsonb
);

alter table public.workers
  add column if not exists deskripsi text,
  add column if not exists pengalaman text,
  add column if not exists keahlian text[] not null default '{}',
  add column if not exists portofolio text,
  add column if not exists reviews jsonb not null default '[]'::jsonb;

alter table public.workers enable row level security;

grant select (id, nama, kategori, kecamatan, tarif_harian, is_verified, is_available,
  rating, total_job, deskripsi, pengalaman, keahlian, portofolio, reviews)
  on table public.workers to anon;

